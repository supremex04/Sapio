package com.ved.study.read;

/**
 * How a section is rewritten for the learner. EXPAND elaborates: explains why and how, breaks complex ideas into
 * steps, adds examples and analogies (elaboration). REVISION condenses: key points, definitions and must-remember
 * facts for quick review (retrieval cues for spaced revision).
 */
public enum NoteStyle {
    EXPAND,
    REVISION
}
